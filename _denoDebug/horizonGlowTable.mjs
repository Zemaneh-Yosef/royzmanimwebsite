// Builds the tables in assets/libraries/kosherZmanim/horizon-glow.js. Run with Node or Deno:
//     node _denoDebug/horizonGlowTable.mjs
// and paste its output over the "generated" block of horizon-glow.js.
//
// The glow: sunlight scattered once by the air (Rayleigh, 550 nm) along the line of sight toward the Sun's
// azimuth, the sunlight dimmed along its own path (Rayleigh + ozone) and cut off by the Earth, the scattered
// light dimmed on its way to the observer (Rayleigh + ozone). Spherical Earth, sea-level observer. No
// aerosol: by the time the Sun is ~10 degrees down every sunlit point on the line of sight is far above the
// haze layer, so haze only dims the glow on the way to the eye; horizon-glow.js applies that at run time.
//
// Single scattering fades too fast in deep twilight (it leaves out light scattered more than once), so the
// fall-off with depression is scaled to match the measured twilight table that star-nightfall.js uses
// (halakhic_calc's), at the horizon toward the Sun, between 12 and 15 degrees down (the deepest part of
// that table).

import { twilightLuminance } from "../assets/libraries/kosherZmanim/star-nightfall.js";

const R = 6371, HR = 8.0, HA = 1.5, TAU_R = 0.0973, TAU_O3 = 0.027, ZO = 22, SO = 6, ZTOP = 150, D2R = Math.PI / 180;
const ozNorm = TAU_O3 / (SO * Math.sqrt(2 * Math.PI));
const bR = z => TAU_R / HR * Math.exp(-z / HR);
const aO = z => ozNorm * Math.exp(-0.5 * ((z - ZO) / SO) ** 2);
const ext = z => bR(z) + aO(z);

/** distance along a ray from inside a sphere of radius rad to its surface */
function exitDist(px, py, ux, uy, rad) {
	const b = px * ux + py * uy, c = px * px + py * py - rad * rad;
	return -b + Math.sqrt(b * b - c);
}

/** sunlight reaching (px, py) along direction (ux, uy) toward the Sun; 0 if the Earth is in the way */
function tSun(px, py, ux, uy) {
	const b = px * ux + py * uy, c = px * px + py * py - R * R;
	if (b < 0 && b * b - c > 0) return 0;
	const L = exitDist(px, py, ux, uy, R + ZTOP), N = 500, h = L / N;
	let tau = 0;
	for (let i = 0; i <= N; i++) {
		const z = Math.hypot(px + ux * h * i, py + uy * h * i) - R;
		tau += (i === 0 || i === N ? 0.5 : 1) * ext(z);
	}
	return Math.exp(-tau * h);
}

/** single-scattered radiance (arbitrary units) at altitude a, toward the Sun's azimuth, Sun D degrees down */
function glow(D, a) {
	const ux = Math.cos(D * D2R), uy = -Math.sin(D * D2R), lx = Math.cos(a * D2R), ly = Math.sin(a * D2R);
	const c = ux * lx + uy * ly, phase = 3 / (16 * Math.PI) * (1 + c * c);
	const S = exitDist(0, R, lx, ly, R + ZTOP), N = 2000, h = S / N;
	let tauObs = 0, sum = 0;
	for (let i = 0; i <= N; i++) {
		const x = lx * h * i, y = R + ly * h * i, z = Math.hypot(x, y) - R;
		sum += (i === 0 || i === N ? 0.5 : 1) * bR(z) * phase * tSun(x, y, ux, uy) * Math.exp(-tauObs);
		tauObs += ext(z) * h;
	}
	return sum * h;
}

/** airmass of an exponential layer of scale height H (km) at altitude a, spherical (relative to vertical) */
function layerAirmass(a, H) {
	const lx = Math.cos(a * D2R), ly = Math.sin(a * D2R);
	const S = exitDist(0, R, lx, ly, R + 40 * H), N = 20000, h = S / N;
	let sum = 0;
	for (let i = 0; i <= N; i++) {
		const z = Math.hypot(lx * h * i, R + ly * h * i) - R;
		sum += (i === 0 || i === N ? 0.5 : 1) * Math.exp(-z / H);
	}
	return sum * h / H;
}

const ALT = [0.5, 1, 1.5, 2, 2.5, 3, 3.5, 4, 5, 6, 7, 8, 10, 12];
const DEP = [];
for (let d = 10; d <= 22.0001; d += 0.5) DEP.push(+d.toFixed(1));

// fall-off scale: measured table vs single scattering, horizon toward the Sun, 12 -> 15 degrees down
const measured = Math.log10(twilightLuminance(0, 0, -12)) - Math.log10(twilightLuminance(0, 0, -15));
const single = Math.log10(glow(12, 1)) - Math.log10(glow(15, 1));
const FALLOFF = measured / single;

const D_REF = 15;
const rows = ALT.map(a => {
	const ref = Math.log10(glow(D_REF, a));
	return DEP.map(D => {
		const g = glow(D, a);
		return g > 0 ? +(ref + FALLOFF * (Math.log10(g) - ref)).toFixed(3) : -30;
	});
});

const fmt = arr => "[" + arr.join(", ") + "]";
console.log(`// generated by _denoDebug/horizonGlowTable.mjs (fall-off scale ${FALLOFF.toFixed(4)}: measured ${measured.toFixed(4)} / single scattering ${single.toFixed(4)} dex, 12 -> 15 deg)`);
console.log(`const GLOW_FALLOFF = ${FALLOFF.toFixed(4)};`);
console.log(`const GLOW_ALT = ${fmt(ALT)};`);
console.log(`const GLOW_DEP = ${fmt(DEP)};`);
console.log(`/** log10 glow (relative), [altitude][depression]; sea-level Rayleigh + ozone included */`);
console.log(`const GLOW_LOG = [\n${rows.map(r => "\t" + fmt(r)).join(",\n")}\n];`);
console.log(`/** airmass of the air (H ${HR} km) and of the haze (H ${HA} km) at each GLOW_ALT */`);
console.log(`const AIRMASS_AIR = ${fmt(ALT.map(a => +layerAirmass(a, HR).toFixed(3)))};`);
console.log(`const AIRMASS_HAZE = ${fmt(ALT.map(a => +layerAirmass(a, HA).toFixed(3)))};`);
